package com.wellness.service;

import com.wellness.dto.MLHealthResponse;
import com.wellness.dto.MLPredictionResponse;
import com.wellness.model.MLPrediction;
import com.wellness.model.RiskLevel;
import com.wellness.repository.MLPredictionRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.boot.web.client.RestTemplateBuilder;
import org.springframework.http.HttpEntity;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.client.ResourceAccessException;
import org.springframework.web.client.RestTemplate;

import java.time.Duration;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
public class MLPredictionServiceTest {

    @Mock
    private MLPredictionRepository predictionRepository;

    @Mock
    private RestTemplate restTemplate;

    private MLPredictionService mlPredictionService;

    @BeforeEach
    void setUp() {
        mlPredictionService = new MLPredictionService(
                predictionRepository,
                restTemplate,
                "http://localhost:8000"
        );

        lenient().when(predictionRepository.save(any(MLPrediction.class))).thenAnswer(invocation -> invocation.getArgument(0));
    }

    @Test
    void testSuccessfulPrediction() {
        MLPredictionResponse mockResponse = new MLPredictionResponse();
        mockResponse.setPrediction("HIGH");
        mockResponse.setProbability(0.92);
        mockResponse.setClassProbabilities(Map.of("HIGH", 0.92, "MODERATE", 0.08));
        mockResponse.setModelVersion("v1.0");
        mockResponse.setContributingFactors(List.of(Map.of("label", "Academic Pressure", "impactScore", 42.0)));
        mockResponse.setScreeningDisclaimer("Screening Disclaimer: Generated by ML Model.");

        when(restTemplate.postForEntity(eq("http://localhost:8000/predict"), any(HttpEntity.class), eq(MLPredictionResponse.class)))
                .thenReturn(new ResponseEntity<>(mockResponse, HttpStatus.OK));

        Map<String, Object> features = new HashMap<>();
        features.put("Stress_Level", 8.0);
        features.put("Wellness_Score", 42.0);

        MLPrediction result = mlPredictionService.predictWellnessRisk("stu_123", "assess_456", features);

        assertNotNull(result);
        assertEquals(RiskLevel.HIGH, result.getPrediction());
        assertEquals(0.92, result.getProbability());
        assertEquals("v1.0", result.getModelVersion());
        assertEquals("SUCCESS", result.getStatus());

        ArgumentCaptor<MLPrediction> captor = ArgumentCaptor.forClass(MLPrediction.class);
        verify(predictionRepository).save(captor.capture());
        assertEquals(RiskLevel.HIGH, captor.getValue().getPrediction());
    }

    @Test
    void testServiceUnavailableStrictNoFallback() {
        // When ML service fails / throws exception
        when(restTemplate.postForEntity(eq("http://localhost:8000/predict"), any(HttpEntity.class), eq(MLPredictionResponse.class)))
                .thenThrow(new ResourceAccessException("Connection refused: connect to port 8000"));

        Map<String, Object> features = new HashMap<>();
        features.put("Stress_Level", 9.0);
        features.put("Wellness_Score", 20.0);

        MLPrediction result = mlPredictionService.predictWellnessRisk("stu_123", "assess_456", features);

        assertNotNull(result);
        // STRICT: MUST NOT FALLBACK TO ANY HEURISTIC PREDICTION
        assertNull(result.getPrediction());
        assertNull(result.getProbability());
        assertEquals("UNAVAILABLE", result.getStatus());
        assertTrue(result.getScreeningDisclaimer().contains("unavailable"));

        ArgumentCaptor<MLPrediction> captor = ArgumentCaptor.forClass(MLPrediction.class);
        verify(predictionRepository).save(captor.capture());
        assertEquals("UNAVAILABLE", captor.getValue().getStatus());
        assertNull(captor.getValue().getPrediction());
    }

    @Test
    void testHealthCheckUp() {
        MLHealthResponse mockHealth = new MLHealthResponse();
        mockHealth.setStatus("UP");
        mockHealth.setModelLoaded(true);
        mockHealth.setModelVersion("v1.0");

        when(restTemplate.getForEntity("http://localhost:8000/health", MLHealthResponse.class))
                .thenReturn(new ResponseEntity<>(mockHealth, HttpStatus.OK));

        MLHealthResponse health = mlPredictionService.checkHealth();
        assertNotNull(health);
        assertEquals("UP", health.getStatus());
        assertTrue(health.isModelLoaded());
    }

    @Test
    void testHealthCheckDown() {
        when(restTemplate.getForEntity("http://localhost:8000/health", MLHealthResponse.class))
                .thenThrow(new ResourceAccessException("Connection refused"));

        MLHealthResponse health = mlPredictionService.checkHealth();
        assertNotNull(health);
        assertEquals("DOWN", health.getStatus());
        assertFalse(health.isModelLoaded());
    }
}
